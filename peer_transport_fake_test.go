package main

import (
	"fmt"
	"sync"
)

// fakeMediaTrack is an in-memory stand-in for *webrtc.TrackLocalStaticRTP.
// Its identity (the id) lets tests assert which source a sink received its
// tracks from, without any real WebRTC peer.
type fakeMediaTrack struct {
	id       string
	streamID string
}

func (t *fakeMediaTrack) ID() string       { return t.id }
func (t *fakeMediaTrack) StreamID() string { return t.streamID }

// fakeSourcePeer records signaling-level interactions instead of creating a
// real WebRTC peer connection. The test drives readiness and disconnection
// explicitly.
type fakeSourcePeer struct {
	source *WRTC_Source

	mutex        sync.Mutex
	closed       bool
	started      bool
	answers      []string
	candidates   []string
	videoTrack   *fakeMediaTrack
	audioTrack   *fakeMediaTrack
	disconnected bool
}

var (
	fakeTrackCounterMu sync.Mutex
	fakeTrackCounter   int
)

func nextFakeTrackID(kind string) string {
	fakeTrackCounterMu.Lock()
	defer fakeTrackCounterMu.Unlock()
	fakeTrackCounter++
	return fmt.Sprintf("fake-%s-%d", kind, fakeTrackCounter)
}

func newFakeSourcePeer(source *WRTC_Source) sourcePeer {
	return &fakeSourcePeer{source: source}
}

func (p *fakeSourcePeer) start() {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if p.closed {
		return
	}

	p.started = true

	// Emulate the OFFER generated by the real transport.
	p.source.connection.sendOffer(p.source.requestId, p.source.sid, `{"type":"offer","fake":true}`)
}

// simulateReady emulates the publisher completing the handshake and pushing
// the expected tracks, which makes the source "ready".
func (p *fakeSourcePeer) simulateReady() {
	p.mutex.Lock()
	if p.closed || p.disconnected {
		p.mutex.Unlock()
		return
	}

	var video mediaTrack
	var audio mediaTrack

	if p.source.hasVideo {
		p.videoTrack = &fakeMediaTrack{id: nextFakeTrackID("video"), streamID: p.source.sid}
		video = p.videoTrack
	}
	if p.source.hasAudio {
		p.audioTrack = &fakeMediaTrack{id: nextFakeTrackID("audio"), streamID: p.source.sid}
		audio = p.audioTrack
	}
	p.mutex.Unlock()

	p.source.markReady(video, audio)
}

// simulateDisconnect emulates the underlying WebRTC transport failing.
func (p *fakeSourcePeer) simulateDisconnect() {
	p.mutex.Lock()
	if p.closed || p.disconnected {
		p.mutex.Unlock()
		return
	}
	p.disconnected = true
	p.mutex.Unlock()

	p.source.onPeerDisconnected()
}

func (p *fakeSourcePeer) onAnswer(answerJSON string) {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if p.closed {
		return
	}

	p.answers = append(p.answers, answerJSON)
}

func (p *fakeSourcePeer) onICECandidate(candidateJSON string) {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if p.closed {
		return
	}

	p.candidates = append(p.candidates, candidateJSON)
}

func (p *fakeSourcePeer) close() {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	p.closed = true
}

func (p *fakeSourcePeer) isClosed() bool {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	return p.closed
}

// fakeSinkPeer records the tracks each "connection" was started with so tests
// can verify a sink re-attaches to the replacement source's tracks.
type fakeSinkPeer struct {
	sink *WRTC_Sink

	mutex      sync.Mutex
	closed     bool
	started    bool
	videoTrack *fakeMediaTrack
	audioTrack *fakeMediaTrack
}

func newFakeSinkPeer(sink *WRTC_Sink) sinkPeer {
	return &fakeSinkPeer{sink: sink}
}

func (p *fakeSinkPeer) start(video mediaTrack, audio mediaTrack) {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if p.closed {
		return
	}

	p.started = true

	if video != nil {
		p.videoTrack = video.(*fakeMediaTrack)
	}
	if audio != nil {
		p.audioTrack = audio.(*fakeMediaTrack)
	}

	// Emulate the OFFER generated by the real transport.
	p.sink.connection.sendOffer(p.sink.requestId, p.sink.sid, `{"type":"offer","fake":true}`)
}

func (p *fakeSinkPeer) onAnswer(answerJSON string) {}

func (p *fakeSinkPeer) onICECandidate(candidateJSON string) {}

// simulateDisconnect emulates the underlying WebRTC transport failing; the
// sink must attempt to reconnect while it remains active.
func (p *fakeSinkPeer) simulateDisconnect() {
	p.mutex.Lock()
	if p.closed {
		p.mutex.Unlock()
		return
	}
	p.closed = true
	p.mutex.Unlock()

	p.sink.onPeerDisconnected()
}

func (p *fakeSinkPeer) close() {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	p.closed = true
}

func (p *fakeSinkPeer) isClosed() bool {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	return p.closed
}

func (p *fakeSinkPeer) trackIDs() (videoID string, audioID string) {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if p.videoTrack != nil {
		videoID = p.videoTrack.id
	}
	if p.audioTrack != nil {
		audioID = p.audioTrack.id
	}

	return videoID, audioID
}

// fakeTransportFactory wires a node to in-memory peers and keeps a registry
// the test can use to drive them.
type fakeTransportFactory struct {
	mutex   sync.Mutex
	sources map[*WRTC_Source]*fakeSourcePeer
	sinks   map[*WRTC_Sink]*fakeSinkPeer
}

func newFakeTransportFactory() *fakeTransportFactory {
	return &fakeTransportFactory{
		sources: make(map[*WRTC_Source]*fakeSourcePeer),
		sinks:   make(map[*WRTC_Sink]*fakeSinkPeer),
	}
}

func (f *fakeTransportFactory) sourceFactory() sourcePeerFactory {
	return func(source *WRTC_Source) sourcePeer {
		fp := newFakeSourcePeer(source)
		f.mutex.Lock()
		f.sources[source] = fp.(*fakeSourcePeer)
		f.mutex.Unlock()
		return fp
	}
}

func (f *fakeTransportFactory) sinkFactory() sinkPeerFactory {
	return func(sink *WRTC_Sink) sinkPeer {
		fp := newFakeSinkPeer(sink)
		f.mutex.Lock()
		f.sinks[sink] = fp.(*fakeSinkPeer)
		f.mutex.Unlock()
		return fp
	}
}

func (f *fakeTransportFactory) fakeSource(source *WRTC_Source) *fakeSourcePeer {
	f.mutex.Lock()
	defer f.mutex.Unlock()

	return f.sources[source]
}

func (f *fakeTransportFactory) fakeSink(sink *WRTC_Sink) *fakeSinkPeer {
	f.mutex.Lock()
	defer f.mutex.Unlock()

	return f.sinks[sink]
}

func (f *fakeTransportFactory) sourceCount() int {
	f.mutex.Lock()
	defer f.mutex.Unlock()

	return len(f.sources)
}

func (f *fakeTransportFactory) sinkCount() int {
	f.mutex.Lock()
	defer f.mutex.Unlock()

	return len(f.sinks)
}
